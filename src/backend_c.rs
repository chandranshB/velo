pub static EMBEDDED_RT_LIB: &[u8] = include_bytes!(env!("VELO_RT_LIB"));

pub fn emit_c_source(prog: &IrProgram) -> String {
    let mut c = String::with_capacity(16 * 1024);
    c.push_str("/* Generated by Velo Compiler (Max-Opt Backend) */\n");
    c.push_str("#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n\n");
    c.push_str("#if defined(_MSC_VER)\n#define VELO_RESTRICT __restrict\n#define VELO_INLINE __forceinline\n#else\n#define VELO_RESTRICT restrict\n#define VELO_INLINE inline\n#endif\n\n");

    // Base str & slice types
    c.push_str("typedef struct { const uint8_t* ptr; int64_t len; } velo_str;\n");
    for (tid_idx, st) in prog.arena.structs.iter().enumerate() {
        let _ = writeln!(c, "typedef struct {} {};", st.c_name, st.c_name);
        let _ = tid_idx;
    }

    // Emit slice typedefs and array typedefs used across program
    emit_compound_typedefs(&mut c, prog);

    // Emit struct definitions (fields sorted by offset; types already computed cleanly)
    for st in &prog.arena.structs {
        let _ = writeln!(c, "struct {} {{", st.c_name);
        for f in &st.fields {
            let fty = c_type(&prog.arena, f.ty);
            let _ = writeln!(c, "    {} {};", fty, sanitize_c_field(&f.name));
        }
        if st.fields.is_empty() {
            c.push_str("    uint8_t _dummy;\n");
        }
        c.push_str("};\n\n");
    }

    // Runtime functions from velo_rt.lib
    c.push_str(
        "void velo_rt_print_i64(int64_t v);\n\
         void velo_rt_print_u64(uint64_t v);\n\
         void velo_rt_print_f64(double v);\n\
         void velo_rt_print_bool(int8_t v);\n\
         void velo_rt_print_str(const uint8_t* ptr, int64_t len);\n\
         void velo_rt_print_cstr(const char* s);\n\
         void velo_rt_print_newline(void);\n\
         void velo_rt_print_space(void);\n\
         void velo_rt_panic(const uint8_t* ptr, int64_t len, const uint8_t* fp, int64_t fl, int64_t line);\n\
         void velo_rt_bounds_fail(int64_t idx, int64_t len, const uint8_t* fp, int64_t fl, int64_t line);\n\
         void* velo_rt_alloc(int64_t bytes);\n\
         void* velo_rt_realloc(void* p, int64_t bytes);\n\
         void velo_rt_free(void* p);\n\
         void velo_rt_copy_mem(void* dst, const void* src, int64_t bytes);\n\
         void velo_rt_set_mem(void* dst, uint8_t val, int64_t bytes);\n\
         int64_t velo_rt_time_ns(void);\n\
         void velo_rt_sleep_ms(int32_t ms);\n\
         uint64_t velo_rt_rand_u64(void);\n\
         int64_t velo_rt_rand_range(int64_t min_v, int64_t max_v);\n\
         int64_t velo_rt_read_int(void);\n\
         int64_t velo_rt_read_line(uint8_t** out_ptr);\n\
         void velo_rt_str_concat(const uint8_t* ap, int64_t al, const uint8_t* bp, int64_t bl, uint8_t** op, int64_t* ol);\n\
         void velo_rt_i64_to_str(int64_t v, uint8_t** op, int64_t* ol);\n\
         void velo_rt_u64_to_str(uint64_t v, uint8_t** op, int64_t* ol);\n\
         void velo_rt_f64_to_str(double v, int32_t prec, uint8_t** op, int64_t* ol);\n\
         void velo_rt_bool_to_str(int8_t v, uint8_t** op, int64_t* ol);\n\
         int8_t velo_rt_str_eq(const uint8_t* ap, int64_t al, const uint8_t* bp, int64_t bl);\n\
         int32_t velo_rt_str_cmp(const uint8_t* ap, int64_t al, const uint8_t* bp, int64_t bl);\n\
         int64_t velo_rt_cstr_len(const char* s);\n\
         double velo_rt_sqrt(double x);\n\
         double velo_rt_sin(double x);\n\
         double velo_rt_cos(double x);\n\
         double velo_rt_tan(double x);\n\
         double velo_rt_floor(double x);\n\
         double velo_rt_ceil(double x);\n\
         double velo_rt_round(double x);\n\
         double velo_rt_pow(double x, double y);\n\n",
    );

    // Extern declarations (stdcall/cdecl on Win64 is uniform fastcall)
    for ex in &prog.externs {
        let ret = c_type(&prog.arena, ex.ret);
        let mut ps = Vec::new();
        for p in &ex.params {
            ps.push(c_type(&prog.arena, *p));
        }
        if ex.variadic {
            ps.push("...".to_string());
        } else if ps.is_empty() {
            ps.push("void".to_string());
        }
        let _ = writeln!(c, "{} {}({});", ret, ex.name, ps.join(", "));
    }
    c.push('\n');

    // Static string and wide-string literals
    for (i, s) in prog.str_lits.iter().enumerate() {
        let escaped = escape_c_bytes(s.as_bytes());
        let _ = writeln!(c, "static const uint8_t velo_lit_{i}[] = \"{escaped}\";");
        let _ = writeln!(
            c,
            "static const velo_str velo_str_lit_{i} = {{ velo_lit_{i}, {} }};",
            s.len()
        );
    }
    for (i, ws) in prog.wstr_lits.iter().enumerate() {
        let vals: Vec<String> = ws.iter().map(|u| format!("{u}u")).collect();
        let _ = writeln!(
            c,
            "static const uint16_t velo_wlit_{i}[] = {{ {} }};",
            vals.join(", ")
        );
    }
    c.push('\n');

    // Function forward declarations
    for f in &prog.funcs {
        emit_fn_sig(&mut c, prog, f, false);
        c.push_str(";\n");
    }
    c.push('\n');

    // Function definitions
    for f in &prog.funcs {
        emit_fn_sig(&mut c, prog, f, false);
        c.push_str(" {\n");
        emit_fn_body(&mut c, prog, f);
        c.push_str("}\n\n");
    }

    // Entry wrapper
    if let Some(main_id) = prog.main_fn {
        let mf = &prog.funcs[main_id.0];
        if mf.ret == TY_VOID {
            let _ = writeln!(
                c,
                "int main(int argc, char** argv) {{ (void)argc; (void)argv; {}(); return 0; }}",
                mf.c_name
            );
        } else {
            let _ = writeln!(
                c,
                "int main(int argc, char** argv) {{ (void)argc; (void)argv; return (int){}(); }}",
                mf.c_name
            );
        }
    }

    c
}

pub fn build_with_msvc_max(
    prog: &IrProgram,
    out_exe: &Path,
    tc: &WindowsToolchain,
    extra_links: &[String],
) -> Result<(), String> {
    let cl = tc
        .cl_exe
        .as_ref()
        .ok_or_else(|| "MSVC cl.exe not found for --backend=max".to_string())?;
    let link = tc
        .link_exe
        .as_ref()
        .or(tc.lld_link_exe.as_ref())
        .ok_or_else(|| "No Windows linker found".to_string())?;

    let c_src = emit_c_source(prog);
    let tmp_dir = std::env::temp_dir().join("velo_build");
    fs::create_dir_all(&tmp_dir).map_err(|e| format!("failed to create build dir: {e}"))?;

    let stem = out_exe
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("velo_app");
    let c_path = tmp_dir.join(format!("{stem}.c"));
    let obj_path = tmp_dir.join(format!("{stem}.obj"));
    let rt_lib_path = tmp_dir.join("velo_rt.lib");

    fs::write(&c_path, c_src).map_err(|e| format!("failed to write C file: {e}"))?;
    fs::write(&rt_lib_path, EMBEDDED_RT_LIB).map_err(|e| format!("failed to write rt lib: {e}"))?;

    let mut cl_cmd = Command::new(cl);
    cl_cmd
        .arg("/nologo")
        .arg("/c")
        .arg("/O2")
        .arg("/Oi")
        .arg("/Ot")
        .arg("/Ob3")
        .arg("/arch:AVX2")
        .arg("/W0")
        .arg(format!("/Fo{}", obj_path.display()))
        .arg(&c_path);

    for inc in tc.include_paths() {
        cl_cmd.arg(format!("/I{}", inc.display()));
    }

    let cl_out = cl_cmd
        .output()
        .map_err(|e| format!("failed to launch cl.exe: {e}"))?;
    if !cl_out.status.success() {
        return Err(format!(
            "cl.exe failed:\n{}\n{}",
            String::from_utf8_lossy(&cl_out.stdout),
            String::from_utf8_lossy(&cl_out.stderr)
        ));
    }

    let mut lnk_cmd = Command::new(link);
    lnk_cmd
        .arg("/NOLOGO")
        .arg(format!("/OUT:{}", out_exe.display()))
        .arg("/OPT:REF")
        .arg("/OPT:ICF");

    match prog.subsystem {
        Subsystem::Windows => {
            lnk_cmd.arg("/SUBSYSTEM:WINDOWS").arg("/ENTRY:mainCRTStartup");
        }
        Subsystem::Console => {
            lnk_cmd.arg("/SUBSYSTEM:CONSOLE");
        }
    }

    for lp in tc.lib_paths() {
        lnk_cmd.arg(format!("/LIBPATH:{}", lp.display()));
    }

    lnk_cmd.arg(&obj_path).arg(&rt_lib_path);
    lnk_cmd
        .arg("kernel32.lib")
        .arg("ucrt.lib")
        .arg("vcruntime.lib")
        .arg("msvcrt.lib")
        .arg("legacy_stdio_definitions.lib");

    for lib in &prog.links {
        let l = if lib.ends_with(".lib") { lib.clone() } else { format!("{lib}.lib") };
        lnk_cmd.arg(l);
    }
    for lib in extra_links {
        let l = if lib.ends_with(".lib") { lib.clone() } else { format!("{lib}.lib") };
        lnk_cmd.arg(l);
    }

    let lnk_out = lnk_cmd
        .output()
        .map_err(|e| format!("failed to run linker: {e}"))?;
    if !lnk_out.status.success() {
        return Err(format!(
            "linker failed:\n{}\n{}",
            String::from_utf8_lossy(&lnk_out.stdout),
            String::from_utf8_lossy(&lnk_out.stderr)
        ));
    }
    Ok(())
}

fn emit_compound_typedefs(c: &mut String, prog: &IrProgram) {
    let mut emitted_slices = std::collections::HashSet::new();
    let mut emitted_arrays = std::collections::HashSet::new();
    let mut emitted_fns = std::collections::HashSet::new();
    for f in &prog.funcs {
        for &vt in &f.vreg_types {
            collect_typedefs(c, &prog.arena, vt, &mut emitted_slices, &mut emitted_arrays, &mut emitted_fns);
        }
        for sl in &f.slots {
            collect_typedefs(c, &prog.arena, sl.ty, &mut emitted_slices, &mut emitted_arrays, &mut emitted_fns);
        }
        collect_typedefs(c, &prog.arena, f.ret, &mut emitted_slices, &mut emitted_arrays, &mut emitted_fns);
    }
    for st in &prog.arena.structs {
        for field in &st.fields {
            collect_typedefs(c, &prog.arena, field.ty, &mut emitted_slices, &mut emitted_arrays, &mut emitted_fns);
        }
    }
    c.push('\n');
}

fn collect_typedefs(
    c: &mut String,
    arena: &TypeArena,
    ty: TypeId,
    slices: &mut std::collections::HashSet<TypeId>,
    arrays: &mut std::collections::HashSet<(TypeId, u64)>,
    fns: &mut std::collections::HashSet<TypeId>,
) {
    match arena.kind(ty).clone() {
        TypeKind::Ptr(inner) => collect_typedefs(c, arena, inner, slices, arrays, fns),
        TypeKind::Slice(el) => {
            collect_typedefs(c, arena, el, slices, arrays, fns);
            if slices.insert(ty) {
                let _ = writeln!(
                    c,
                    "typedef struct {{ {}* ptr; int64_t len; }} velo_slice_{};",
                    c_type(arena, el),
                    ty.0
                );
            }
        }
        TypeKind::Array(el, len) => {
            collect_typedefs(c, arena, el, slices, arrays, fns);
            if arrays.insert((el, len)) {
                let _ = writeln!(
                    c,
                    "typedef struct {{ {} data[{}]; }} velo_arr_{}_{};",
                    c_type(arena, el),
                    len.max(1),
                    el.0,
                    len
                );
            }
        }
        TypeKind::Fn(params, ret) => {
            for p in &params {
                collect_typedefs(c, arena, *p, slices, arrays, fns);
            }
            collect_typedefs(c, arena, ret, slices, arrays, fns);
            if fns.insert(ty) {
                let ps: Vec<String> = if params.is_empty() {
                    vec!["void".into()]
                } else {
                    params.iter().map(|p| c_type(arena, *p)).collect()
                };
                let _ = writeln!(
                    c,
                    "typedef {} (*velo_fn_{})({});",
                    c_type(arena, ret),
                    ty.0,
                    ps.join(", ")
                );
            }
        }
        _ => {}
    }
}

fn c_type(arena: &TypeArena, id: TypeId) -> String {
    match arena.kind(id) {
        TypeKind::Void => "void".into(),
        TypeKind::Bool => "int8_t".into(),
        TypeKind::I8 => "int8_t".into(),
        TypeKind::I16 => "int16_t".into(),
        TypeKind::I32 => "int32_t".into(),
        TypeKind::I64 => "int64_t".into(),
        TypeKind::U8 => "uint8_t".into(),
        TypeKind::U16 => "uint16_t".into(),
        TypeKind::U32 => "uint32_t".into(),
        TypeKind::U64 => "uint64_t".into(),
        TypeKind::F32 => "float".into(),
        TypeKind::F64 => "double".into(),
        TypeKind::OpaquePtr => "void*".into(),
        TypeKind::CStr => "const char*".into(),
        TypeKind::Str => "velo_str".into(),
        TypeKind::Ptr(inner) => format!("{}*", c_type(arena, *inner)),
        TypeKind::Slice(_) => format!("velo_slice_{}", id.0),
        TypeKind::Array(el, len) => format!("velo_arr_{}_{}", el.0, len),
        TypeKind::Struct(sid) => arena.structs[sid.0].c_name.clone(),
        TypeKind::Enum(eid) => c_type(arena, arena.enums[eid.0].repr),
        TypeKind::Fn(_, _) => format!("velo_fn_{}", id.0),
    }
}

fn c_val_type(arena: &TypeArena, id: TypeId) -> String {
    if arena.is_aggregate(id) {
        format!("{}*", c_type(arena, id))
    } else {
        c_type(arena, id)
    }
}

fn emit_fn_sig(c: &mut String, prog: &IrProgram, f: &IrFunction, _inline: bool) {
    let ret = c_type(&prog.arena, f.ret);
    let mut ps = Vec::new();
    for p in &f.params {
        let base_t = c_type(&prog.arena, p.ty);
        let p_str = if prog.arena.is_aggregate(p.ty) {
            format!("{base_t} p_{}", p.slot.0)
        } else if p.noalias && prog.arena.is_ptr_like(p.ty) && !matches!(prog.arena.kind(p.ty), TypeKind::Fn(_, _)) {
            format!("{base_t} VELO_RESTRICT p_{}", p.slot.0)
        } else {
            format!("{base_t} p_{}", p.slot.0)
        };
        ps.push(p_str);
    }
    if ps.is_empty() {
        ps.push("void".to_string());
    }
    let _ = write!(c, "{} {}({})", ret, f.c_name, ps.join(", "));
}

fn emit_fn_body(c: &mut String, prog: &IrProgram, f: &IrFunction) {
    for sl in &f.slots {
        let ty_s = c_type(&prog.arena, sl.ty);
        let _ = writeln!(c, "    {} s_{};", ty_s, sl.id.0);
    }
    for p in &f.params {
        let _ = writeln!(c, "    s_{} = p_{};", p.slot.0, p.slot.0);
    }
    for (vi, &vt) in f.vreg_types.iter().enumerate() {
        if vt == TY_VOID {
            continue;
        }
        let vt_s = c_val_type(&prog.arena, vt);
        let _ = writeln!(c, "    {} v_{};", vt_s, vi);
        if prog.arena.is_aggregate(vt) {
            let ct = c_type(&prog.arena, vt);
            let _ = writeln!(c, "    {} _ret_slot_{};", ct, vi);
        }
    }

    for bb in &f.blocks {
        let _ = writeln!(c, "bb_{}:;", bb.id.0);
        for inst in &bb.insts {
            emit_inst(c, prog, f, inst);
        }
        match &bb.term {
            IrTerm::Jump(t) => {
                let _ = writeln!(c, "    goto bb_{};", t.0);
            }
            IrTerm::BranchIf { cond, then_bb, else_bb } => {
                let _ = writeln!(
                    c,
                    "    if (v_{}) goto bb_{}; else goto bb_{};",
                    cond.0, then_bb.0, else_bb.0
                );
            }
            IrTerm::Return(opt) => match opt {
                None => c.push_str("    return;\n"),
                Some(v) => {
                    if prog.arena.is_aggregate(f.ret) {
                        let _ = writeln!(c, "    return *v_{};", v.0);
                    } else {
                        let _ = writeln!(c, "    return v_{};", v.0);
                    }
                }
            },
            IrTerm::Unreachable => {
                c.push_str("    ;\n");
            }
        }
    }
}

fn emit_inst(c: &mut String, prog: &IrProgram, f: &IrFunction, inst: &IrInst) {
    match inst {
        IrInst::ConstInt { dst, ty, val } => {
            let ct = c_type(&prog.arena, *ty);
            if *val == i64::MIN as i128 {
                let _ = writeln!(c, "    v_{} = ({ct})(-9223372036854775807LL - 1);", dst.0);
            } else {
                let _ = writeln!(c, "    v_{} = ({ct})({val}LL);", dst.0);
            }
        }
        IrInst::ConstFloat { dst, ty, val } => {
            let ct = c_type(&prog.arena, *ty);
            if val.is_finite() {
                let _ = writeln!(c, "    v_{} = ({ct})({val:?});", dst.0);
            } else {
                let _ = writeln!(c, "    v_{} = ({ct})0.0;", dst.0);
            }
        }
        IrInst::ConstBool { dst, val } => {
            let _ = writeln!(c, "    v_{} = {};", dst.0, if *val { 1 } else { 0 });
        }
        IrInst::ConstNull { dst, ty } => {
            let ct = c_type(&prog.arena, *ty);
            let _ = writeln!(c, "    v_{} = ({ct})0;", dst.0);
        }
        IrInst::ConstStr { dst, lit } => {
            let _ = writeln!(c, "    v_{} = (velo_str*)&velo_str_lit_{};", dst.0, lit.0);
        }
        IrInst::ConstCStr { dst, lit } => {
            let _ = writeln!(c, "    v_{} = (const char*)velo_lit_{};", dst.0, lit.0);
        }
        IrInst::ConstWStr { dst, lit } => {
            let _ = writeln!(c, "    v_{} = (uint16_t*)velo_wlit_{};", dst.0, lit);
        }
        IrInst::FnAddr { dst, func, ty } => {
            let ct = c_type(&prog.arena, *ty);
            let _ = writeln!(c, "    v_{} = ({ct})&{};", dst.0, prog.funcs[func.0].c_name);
        }
        IrInst::Copy { dst, src } => {
            if f.vreg_types[dst.0 as usize] != TY_VOID {
                let _ = writeln!(c, "    v_{} = v_{};", dst.0, src.0);
            }
        }
        IrInst::Unary { dst, op, src, ty } => {
            let ct = c_type(&prog.arena, *ty);
            let op_s = match op {
                UnaryOp::Neg => "-",
                UnaryOp::Not => "!",
                UnaryOp::BitNot => "~",
            };
            let _ = writeln!(c, "    v_{} = ({ct})({op_s}v_{});", dst.0, src.0);
        }
        IrInst::Binary { dst, op, left, right, ty } => {
            let ct = c_type(&prog.arena, *ty);
            let op_s = match op {
                BinOp::Add => "+",
                BinOp::Sub => "-",
                BinOp::Mul => "*",
                BinOp::Div => "/",
                BinOp::Mod => "%",
                BinOp::BitAnd => "&",
                BinOp::BitOr => "|",
                BinOp::BitXor => "^",
                BinOp::Shl => "<<",
                BinOp::Shr => ">>",
                BinOp::Eq => "==",
                BinOp::Ne => "!=",
                BinOp::Lt => "<",
                BinOp::Le => "<=",
                BinOp::Gt => ">",
                BinOp::Ge => ">=",
                BinOp::And => "&&",
                BinOp::Or => "||",
            };
            let _ = writeln!(c, "    v_{} = ({ct})(v_{} {op_s} v_{});", dst.0, left.0, right.0);
        }
        IrInst::Cast { dst, src, from: _, to } => {
            let ct = c_type(&prog.arena, *to);
            if *to == TY_BOOL {
                let _ = writeln!(c, "    v_{} = (int8_t)(v_{} != 0);", dst.0, src.0);
            } else {
                let _ = writeln!(c, "    v_{} = ({ct})(v_{});", dst.0, src.0);
            }
        }
        IrInst::SlotAddr { dst, slot, .. } => {
            let _ = writeln!(c, "    v_{} = &s_{};", dst.0, slot.0);
        }
        IrInst::LoadSlot { dst, slot, .. } => {
            let _ = writeln!(c, "    v_{} = s_{};", dst.0, slot.0);
        }
        IrInst::StoreSlot { slot, val, .. } => {
            let _ = writeln!(c, "    s_{} = v_{};", slot.0, val.0);
        }
        IrInst::ZeroSlot { slot, ty } => {
            let _ = writeln!(c, "    memset(&s_{}, 0, {});", slot.0, prog.arena.layout(*ty).size);
        }
        IrInst::LoadPtr { dst, ptr, ty, .. } => {
            let ct = c_type(&prog.arena, *ty);
            let _ = writeln!(c, "    v_{} = *({ct}*)(v_{});", dst.0, ptr.0);
        }
        IrInst::StorePtr { ptr, val, ty, .. } => {
            let ct = c_type(&prog.arena, *ty);
            let _ = writeln!(c, "    *({ct}*)(v_{}) = v_{};", ptr.0, val.0);
        }
        IrInst::FieldPtr { dst, base_ptr, offset, field_ty } => {
            let pt = format!("{}*", c_type(&prog.arena, *field_ty));
            let _ = writeln!(
                c,
                "    v_{} = ({pt})((uint8_t*)(v_{}) + {offset});",
                dst.0, base_ptr.0
            );
        }
        IrInst::IndexPtr { dst, base_ptr, index, elem_ty, elem_size } => {
            let pt = format!("{}*", c_type(&prog.arena, *elem_ty));
            let _ = writeln!(
                c,
                "    v_{} = ({pt})((uint8_t*)(v_{}) + ((int64_t)v_{}) * {elem_size});",
                dst.0, base_ptr.0, index.0
            );
        }
        IrInst::BoundsCheck { index, len, file_lit, line } => {
            let _ = writeln!(
                c,
                "    if ((uint64_t)v_{} >= (uint64_t)v_{}) velo_rt_bounds_fail((int64_t)v_{}, (int64_t)v_{}, velo_str_lit_{}.ptr, velo_str_lit_{}.len, {line}LL);",
                index.0, len.0, index.0, len.0, file_lit.0, file_lit.0
            );
        }
        IrInst::MemCopy { dst_ptr, src_ptr, bytes } => {
            let _ = writeln!(c, "    memcpy((void*)v_{}, (const void*)v_{}, {bytes});", dst_ptr.0, src_ptr.0);
        }
        IrInst::MemZero { dst_ptr, bytes } => {
            let _ = writeln!(c, "    memset((void*)v_{}, 0, {bytes});", dst_ptr.0);
        }
        IrInst::Call { dst, func, args, ret } => {
            let target = &prog.funcs[func.0];
            let arg_s: Vec<String> = args
                .iter()
                .zip(target.params.iter())
                .map(|(a, p)| {
                    if prog.arena.is_aggregate(p.ty) {
                        format!("*v_{}", a.0)
                    } else {
                        format!("v_{}", a.0)
                    }
                })
                .collect();
            emit_call_assign(c, &prog.arena, *dst, *ret, &format!("{}({})", target.c_name, arg_s.join(", ")));
        }
        IrInst::CallExtern { dst, ext, args, ret } => {
            let target = &prog.externs[ext.0];
            let arg_s: Vec<String> = args
                .iter()
                .enumerate()
                .map(|(i, a)| {
                    if let Some(&pty) = target.params.get(i) {
                        if prog.arena.is_aggregate(pty) {
                            return format!("*v_{}", a.0);
                        }
                    }
                    format!("v_{}", a.0)
                })
                .collect();
            emit_call_assign(c, &prog.arena, *dst, *ret, &format!("{}({})", target.name, arg_s.join(", ")));
        }
        IrInst::CallIndirect { dst, callee, args, fn_ty, ret } => {
            let param_tys = match prog.arena.kind(*fn_ty) {
                TypeKind::Fn(ps, _) => ps.clone(),
                _ => Vec::new(),
            };
            let arg_s: Vec<String> = args
                .iter()
                .zip(param_tys.iter())
                .map(|(a, pty)| {
                    if prog.arena.is_aggregate(*pty) {
                        format!("*v_{}", a.0)
                    } else {
                        format!("v_{}", a.0)
                    }
                })
                .collect();
            emit_call_assign(c, &prog.arena, *dst, *ret, &format!("(v_{})({})", callee.0, arg_s.join(", ")));
        }
        IrInst::RuntimeCall { dst, op, args, ret } => {
            let rt_name = match op {
                RtOp::PrintI64 => "velo_rt_print_i64",
                RtOp::PrintU64 => "velo_rt_print_u64",
                RtOp::PrintF64 => "velo_rt_print_f64",
                RtOp::PrintBool => "velo_rt_print_bool",
                RtOp::PrintStr => "velo_rt_print_str",
                RtOp::PrintCStr => "velo_rt_print_cstr",
                RtOp::PrintNewline => "velo_rt_print_newline",
                RtOp::PrintSpace => "velo_rt_print_space",
                RtOp::Panic => "velo_rt_panic",
                RtOp::Alloc => "velo_rt_alloc",
                RtOp::Realloc => "velo_rt_realloc",
                RtOp::Free => "velo_rt_free",
                RtOp::CopyMem => "velo_rt_copy_mem",
                RtOp::SetMem => "velo_rt_set_mem",
                RtOp::TimeNs => "velo_rt_time_ns",
                RtOp::SleepMs => "velo_rt_sleep_ms",
                RtOp::RandU64 => "velo_rt_rand_u64",
                RtOp::RandRange => "velo_rt_rand_range",
                RtOp::ReadInt => "velo_rt_read_int",
                RtOp::ReadLine => "velo_rt_read_line",
                RtOp::StrConcat => "velo_rt_str_concat",
                RtOp::I64ToStr => "velo_rt_i64_to_str",
                RtOp::U64ToStr => "velo_rt_u64_to_str",
                RtOp::F64ToStr => "velo_rt_f64_to_str",
                RtOp::BoolToStr => "velo_rt_bool_to_str",
                RtOp::StrEq => "velo_rt_str_eq",
                RtOp::StrCmp => "velo_rt_str_cmp",
                RtOp::CStrLen => "velo_rt_cstr_len",
                RtOp::SqrtF64 => "velo_rt_sqrt",
                RtOp::SinF64 => "velo_rt_sin",
                RtOp::CosF64 => "velo_rt_cos",
                RtOp::TanF64 => "velo_rt_tan",
                RtOp::FloorF64 => "velo_rt_floor",
                RtOp::CeilF64 => "velo_rt_ceil",
                RtOp::RoundF64 => "velo_rt_round",
                RtOp::PowF64 => "velo_rt_pow",
            };
            let arg_s: Vec<String> = args.iter().map(|a| format!("v_{}", a.0)).collect();
            let ct = if *ret == TY_VOID { String::new() } else { format!("({})", c_type(&prog.arena, *ret)) };
            if let Some(d) = dst {
                let _ = writeln!(c, "    v_{} = {ct}{rt_name}({});", d.0, arg_s.join(", "));
            } else {
                let _ = writeln!(c, "    {rt_name}({});", arg_s.join(", "));
            }
        }
    }
}

fn emit_call_assign(c: &mut String, arena: &TypeArena, dst: Option<VReg>, ret: TypeId, call_expr: &str) {
    if let Some(d) = dst {
        if arena.is_aggregate(ret) {
            let _ = writeln!(
                c,
                "    _ret_slot_{} = {call_expr}; v_{} = &_ret_slot_{};",
                d.0, d.0, d.0
            );
        } else {
            let _ = writeln!(c, "    v_{} = {call_expr};", d.0);
        }
    } else {
        let _ = writeln!(c, "    {call_expr};");
    }
}

fn sanitize_c_field(s: &str) -> String {
    match s {
        "register" | "auto" | "static" | "extern" | "struct" | "enum" | "union" | "void"
        | "int" | "char" | "long" | "short" | "float" | "double" | "signed" | "unsigned"
        | "const" | "volatile" | "return" | "if" | "else" | "while" | "for" | "do"
        | "switch" | "case" | "default" | "break" | "continue" | "goto" | "sizeof"
        | "typedef" | "inline" | "restrict" => format!("_f_{s}"),
        _ => s.to_string(),
    }
}

fn escape_c_bytes(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for &b in bytes {
        match b {
            b'\\' => out.push_str("\\\\"),
            b'"' => out.push_str("\\\""),
            b'\n' => out.push_str("\\n"),
            b'\r' => out.push_str("\\r"),
            b'\t' => out.push_str("\\t"),
            0x20..=0x7E => out.push(b as char),
            _ => {
                let _ = write!(out, "\\x{b:02x}");
            }
        }
    }
    out
}
